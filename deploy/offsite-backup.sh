#!/usr/bin/env bash
# Upload a completed SQLite snapshot AND the matching deployment secrets to an rclone crypt
# remote, or verify the newest complete remote snapshot in an isolated temporary directory.
# Installed as root by install-offsite-backup.sh; never prints secret contents or credentials.
set -euo pipefail
umask 077

mode="${1:-}"
[[ "$mode" == upload || "$mode" == verify ]] || { echo 'usage: offsite-backup.sh upload|verify' >&2; exit 2; }
: "${OTTO_RCLONE_DEST:?configure an rclone crypt destination in /etc/otto/offsite.env}"
: "${RCLONE_CONFIG:?configure a root-owned rclone config in /etc/otto/offsite.env}"
[[ -f "$RCLONE_CONFIG" && ! -L "$RCLONE_CONFIG" ]] || { echo 'rclone config missing or symlinked' >&2; exit 1; }
[[ "$(stat -c '%u' "$RCLONE_CONFIG")" == 0 ]] || { echo 'rclone config must belong to root' >&2; exit 1; }
config_mode="$(stat -c '%a' "$RCLONE_CONFIG")"
(( (8#$config_mode & 077) == 0 )) || { echo 'rclone config must be private (0600)' >&2; exit 1; }
remote_name="${OTTO_RCLONE_DEST%%:*}"
[[ "$OTTO_RCLONE_DEST" == *:* && "$remote_name" =~ ^[A-Za-z0-9_-]+$ ]] || {
  echo 'destination must be a named rclone crypt remote, e.g. crypt:otto' >&2; exit 1;
}
# Never upload plaintext to an ordinary remote even if the operator mistypes its name.
remote_config="$(rclone --config "$RCLONE_CONFIG" config show "$remote_name")"
if ! grep -Eq '^[[:space:]]*type[[:space:]]*=[[:space:]]*crypt[[:space:]]*$' <<< "$remote_config"; then
  echo 'destination is not an rclone crypt remote; refusing to upload' >&2; exit 1
fi
unset remote_config

backup_dir="${OTTO_BACKUP_DIR:-/var/lib/otto/backups}"
vars_file="${OTTO_VARS_FILE:-/etc/otto/.dev.vars}"
work_dir="$(mktemp -d)"
trap 'rm -rf -- "$work_dir"' EXIT

if [[ "$mode" == upload ]]; then
  [[ -f "$vars_file" && ! -L "$vars_file" ]] || { echo 'deployment secrets missing' >&2; exit 1; }
  # Timestamp names are generated by the existing local backup timer. Reject arbitrary paths.
  latest="$(find "$backup_dir" -maxdepth 1 -type f -name 'steward-*.sqlite' -printf '%T@ %f\n' | sort -nr | head -n 1 | cut -d ' ' -f 2-)"
  [[ "$latest" =~ ^steward-[0-9]{8}T[0-9]{6}\.sqlite$ ]] || { echo 'no valid local SQLite snapshot' >&2; exit 1; }
  id="${latest%.sqlite}"
  [[ "$(sqlite3 "$backup_dir/$latest" 'PRAGMA integrity_check;')" == ok ]] || { echo 'local backup failed SQLite integrity_check' >&2; exit 1; }
  # Snapshot the key file into the private working directory before the first remote write.
  install -m 0600 "$vars_file" "$work_dir/otto.env"
  [[ -s "$work_dir/otto.env" ]] || { echo 'deployment secrets empty' >&2; exit 1; }
  cp -- "$backup_dir/$latest" "$work_dir/steward.sqlite"
  (cd "$work_dir" && sha256sum steward.sqlite otto.env > SHA256SUMS)
  target="${OTTO_RCLONE_DEST%/}/$id"
  rclone --config "$RCLONE_CONFIG" copyto "$work_dir/steward.sqlite" "$target/steward.sqlite"
  rclone --config "$RCLONE_CONFIG" copyto "$work_dir/otto.env" "$target/otto.env"
  # A key rotation during this upload makes the backup pair ambiguous. Leave it incomplete.
  cmp -s -- "$vars_file" "$work_dir/otto.env" || { echo 'deployment secrets changed during upload; retry after rotation' >&2; exit 1; }
  # SHA256SUMS is uploaded last: its presence marks a complete, paired snapshot.
  rclone --config "$RCLONE_CONFIG" copyto "$work_dir/SHA256SUMS" "$target/SHA256SUMS"
  echo "uploaded encrypted offsite snapshot $id"
else
  # Choose the newest directory only after a completion marker exists; ignore partial uploads.
  ids="$(rclone --config "$RCLONE_CONFIG" lsf "${OTTO_RCLONE_DEST%/}/" --dirs-only)"
  id="$(printf '%s\n' "$ids" | tr -d '/' | grep -E '^steward-[0-9]{8}T[0-9]{6}$' | sort | tail -n 1)"
  [[ -n "$id" ]] || { echo 'no remote snapshots' >&2; exit 1; }
  target="${OTTO_RCLONE_DEST%/}/$id"
  for item in SHA256SUMS steward.sqlite otto.env; do
    rclone --config "$RCLONE_CONFIG" copyto "$target/$item" "$work_dir/$item"
  done
  [[ -s "$work_dir/otto.env" ]] || { echo 'restored secrets empty' >&2; exit 1; }
  # Only accept the two expected names; never interpret attacker-controlled paths in a manifest.
  [[ "$(wc -l < "$work_dir/SHA256SUMS")" -eq 2 ]] || { echo 'unexpected backup manifest' >&2; exit 1; }
  grep -Eq '^[a-f0-9]{64} [ *]steward\.sqlite$' "$work_dir/SHA256SUMS" || { echo 'database manifest missing' >&2; exit 1; }
  grep -Eq '^[a-f0-9]{64} [ *]otto\.env$' "$work_dir/SHA256SUMS" || { echo 'secrets manifest missing' >&2; exit 1; }
  (cd "$work_dir" && sha256sum -c SHA256SUMS >/dev/null)
  [[ "$(sqlite3 "$work_dir/steward.sqlite" 'PRAGMA integrity_check;')" == ok ]] || { echo 'restored SQLite failed integrity_check' >&2; exit 1; }
  echo "verified encrypted offsite snapshot $id (database and secrets); no production files changed"
fi
